//! uniffi FFI binding generator for partner SDKs.
//!
//! One command generates bindings for all three languages:
//! ```bash
//! cargo build -p tunnel-core
//! cargo run -p tunnel-core --bin uniffi-bindgen -- \
//!     generate-all --library target/debug/libtunnel_core.so --out-dir bindings
//! ```
//! Result: `bindings/kotlin/`, `bindings/swift/`, `bindings/python/`.
//!
//! A single language — the standard uniffi CLI:
//! ```bash
//! cargo run -p tunnel-core --bin uniffi-bindgen -- \
//!     generate --library <lib> --language swift --out-dir <dir>
//! ```

use std::process::Command;

/// Languages generated by `generate-all`; the order matches the `dist/` SDK.
const LANGUAGES: [&str; 3] = ["kotlin", "swift", "python"];

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.get(1).map(String::as_str) == Some("generate-all") {
        std::process::exit(generate_all(&args));
    }
    uniffi::uniffi_bindgen_main()
}

/// `generate-all --library <path> --out-dir <dir>`: generates bindings for all
/// supported languages into subdirectories named after each language.
/// The implementation shells out to the standard CLI via `current_exe`: more
/// robust across uniffi_bindgen version upgrades than the programmatic API.
fn generate_all(args: &[String]) -> i32 {
    let mut library = None;
    let mut out_dir = None;
    let mut iterator = args.iter();
    while let Some(arg) = iterator.next() {
        match arg.as_str() {
            "--library" => library = iterator.next().cloned(),
            "--out-dir" => out_dir = iterator.next().cloned(),
            _ => {}
        }
    }
    let (Some(library), Some(out_dir)) = (library, out_dir) else {
        eprintln!("usage: uniffi-bindgen generate-all --library <libtunnel_core.so> --out-dir <dir>");
        return 2;
    };

    let exe = match std::env::current_exe() {
        Ok(exe) => exe,
        Err(err) => {
            eprintln!("failed to resolve the uniffi-bindgen path: {err}");
            return 1;
        }
    };

    for language in LANGUAGES {
        let lang_dir = format!("{out_dir}/{language}");
        println!("uniffi-bindgen: generating {language} → {lang_dir}");
        let status = Command::new(&exe)
            .args([
                "generate",
                "--library",
                &library,
                "--language",
                language,
                "--out-dir",
                &lang_dir,
            ])
            .status();
        match status {
            Ok(status) if status.success() => {}
            Ok(status) => {
                eprintln!("uniffi-bindgen: {language} exited with an error ({status})");
                return 1;
            }
            Err(err) => {
                eprintln!("uniffi-bindgen: failed to run generation for {language}: {err}");
                return 1;
            }
        }
    }
    println!("uniffi-bindgen: done → {out_dir}/{{kotlin,swift,python}} (from {library})");
    0
}
